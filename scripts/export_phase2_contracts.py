"""Export v2 JSON Schema plus Java/TS wire types from the Python boundary models.

Run with .venv/bin/python scripts/export_phase2_contracts.py [--check].
Generated types are not registrations: stage 2/3 will opt the runtime into v2.
"""
import json
import re
import sys
from pathlib import Path
from unlockops.common.workflow_contracts import ContractBundle, REASON_STATUSES

ROOT = Path(__file__).resolve().parents[1]
schema = ContractBundle.model_json_schema()
schema['$schema'] = 'https://json-schema.org/draft/2020-12/schema'
schema['$id'] = 'urn:unlockops:contracts:phase2:v2'
defs = schema['$defs']

def nullable(s):
    return any(x.get('type') == 'null' for x in s.get('anyOf', []))

def java_type(s):
    if '$ref' in s: return s['$ref'].split('/')[-1]
    if 'anyOf' in s:
        variants=[x for x in s['anyOf'] if x.get('type')!='null']
        return java_type(variants[0]) if len(variants)==1 else 'Object'
    if 'oneOf' in s: return 'Object'
    if s.get('type')=='array': return 'List<'+java_type(s['items'])+'>'
    return {'integer':'Integer','boolean':'Boolean','number':'BigDecimal','object':'JsonNode'}.get(s.get('type'),'String')

def ts_type(s):
    if '$ref' in s: return s['$ref'].split('/')[-1]
    if 'const' in s: return json.dumps(s['const'])
    if 'enum' in s: return ' | '.join(json.dumps(x) for x in s['enum'])
    if 'anyOf' in s or 'oneOf' in s: return ' | '.join(ts_type(x) for x in s.get('anyOf',s.get('oneOf',[])))
    if s.get('type')=='array': return '('+ts_type(s['items'])+')[]'
    return {'integer':'number','number':'number','boolean':'boolean','null':'null','object':'Record<string, unknown>'}.get(s.get('type'),'string')

def camel(n): return re.sub(r'_([a-z])',lambda m:m[1].upper(),n)

java=['// Generated by scripts/export_phase2_contracts.py; do not edit.',
      'package com.unlockops.contracts.v2;',
      'import com.fasterxml.jackson.annotation.JsonProperty;',
      'import com.fasterxml.jackson.databind.JsonNode;',
      'import jakarta.validation.Valid;',
      'import jakarta.validation.constraints.*;',
      'import java.util.List;', 'import java.math.BigDecimal;',
      'public final class WorkflowTypes {', '    private WorkflowTypes() {}']
ts=['// Generated by scripts/export_phase2_contracts.py; do not edit.']
for name,s in defs.items():
    if 'enum' in s:
        java.append('    public enum '+name+' { '+', '.join(s['enum'])+' }')
        ts.append('export type '+name+' = '+ts_type(s)+';')
        continue
    fields=[]
    ts.append('export interface '+name+' {')
    for key,p in s.get('properties',{}).items():
        required=key in s.get('required',[])
        effective=next((x for x in p.get('anyOf',[]) if x.get('type')!='null'),p)
        annotations=['@JsonProperty("'+key+'")','@Valid']
        if required and not nullable(p): annotations.append('@NotNull')
        if 'minimum' in effective: annotations.append('@Min('+str(effective['minimum'])+')')
        if 'minLength' in effective or 'maxLength' in effective or 'minItems' in effective or 'maxItems' in effective:
            args=[]
            if 'minLength' in effective or 'minItems' in effective: args.append('min='+str(effective.get('minLength',effective.get('minItems'))))
            if 'maxLength' in effective or 'maxItems' in effective: args.append('max='+str(effective.get('maxLength',effective.get('maxItems'))))
            annotations.append('@Size('+', '.join(args)+')')
        pattern=effective.get('pattern')
        if effective.get('format')=='uuid': pattern='^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
        if 'enum' in effective: pattern='^('+'|'.join(effective['enum'])+')$'
        if isinstance(effective.get('const'),str): pattern='^'+effective['const']+'$'
        if pattern: annotations.append('@Pattern(regexp='+json.dumps(pattern)+')')
        if isinstance(effective.get('const'),bool): annotations.append('@AssertTrue' if effective['const'] else '@AssertFalse')
        elif isinstance(effective.get('const'),int): annotations += ['@Min('+str(effective['const'])+')','@Max('+str(effective['const'])+')']
        fields.append('        '+' '.join(annotations)+' '+java_type(p)+' '+camel(key))
        ts.append('  '+key+('' if required else '?')+': '+ts_type(p)+';')
    java.append('    public record '+name+'(\n'+',\n'.join(fields)+'\n    ) {}')
    ts.append('}')
java.append('    public static final java.util.Map<String, String> REASON_STATUSES = java.util.Map.ofEntries(' + ','.join('java.util.Map.entry('+json.dumps(k)+','+json.dumps(v)+')' for k,v in REASON_STATUSES.items()) + ');')
java.append('}')
outputs={ROOT/'contracts/phase2/reason-status.json':json.dumps(REASON_STATUSES,indent=2)+'\n',ROOT/'contracts/phase2/schema.json':json.dumps(schema,ensure_ascii=False,indent=2)+'\n',
ROOT/'backend/src/main/java/com/unlockops/contracts/v2/WorkflowTypes.java':'\n'.join(java)+'\n',
ROOT/'frontend/src/contracts/phase2.ts':'\n'.join(ts)+'\n'}
for path,content in outputs.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text()!=content: raise SystemExit('Stale generated contract: '+str(path))
    else:
        path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content)
print('Phase 2 contract exports verified' if '--check' in sys.argv else 'Phase 2 contracts exported')
