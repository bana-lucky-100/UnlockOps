"""Append policy revision 4: distinguish permission, license and usage budget costs."""
import argparse
import json
from import_phase2_policy import ROOT, DIRECTORY, COPY_COLUMNS, quote, digest


def outputs():
    catalog=json.loads((ROOT/'data/phase2/catalog.json').read_text())
    files={}
    sql=['-- Generated by scripts/align_access_costs.py. Apply after V10 and policy revision 3.',
         'BEGIN;', "SET LOCAL lock_timeout='5s';",
         'LOCK TABLE policy_revisions, pricing_revisions, approval_route_revisions, reclaim_rules, access_cost_rules IN SHARE ROW EXCLUSIVE MODE;']
    licenses={'NOTION':('BUSINESS','COVERED'),'TABLEAU_CLOUD':('EXPLORER','COVERED'),
              'SALESFORCE':('CRM','COVERED'),'FIGMA':('FULL','NOT_COVERED'),'GITHUB':('COPILOT','NOT_COVERED')}
    for company,info in catalog['companies'].items():
        co,policy=quote(info['company_id']),quote(info['policy_id'])
        old=(DIRECTORY/f'company-{company.lower()}-policy-v3.md').read_text()
        content=old.replace('revision 3','revision 4').replace(' | 3 |',' | 4 |')
        content=content.replace('Notion은 Business 플랜 월 20달러, Tableau는 Enterprise Explorer 월 70달러입니다.',
            'Notion Business 월 20달러와 Tableau Enterprise Explorer 월 70달러는 제공 자료의 참고 단가입니다. 기존 라이선스로 가능한 페이지·프로젝트 권한 추가에 이 단가를 재차 부과하지 않습니다.')
        content=content.replace('잔여 예산 100.00 USD에서 예상 예산은 84.00 USD입니다.',
            '신규 Full 좌석 구매가 확인된 경우 잔여 예산 100.00 USD에서 예상 예산은 84.00 USD입니다. 동일 조직에서 필요한 좌석을 이미 보유했다면 추가 비용은 0입니다.')
        content += '''\n## BASELINE | COMMON | 4 | 권한·라이선스·사용량 예산의 구분

권한 추가, 유료 좌석 확보, 사용량 예산 배정을 별도 작업으로 판단한다. 가격표의 월 금액은 참고 단가이며 모든 권한 요청의 추가 비용이 아니다.
서버의 회사·사용자·플랫폼·대상 조직/워크스페이스·필요 라이선스 코드가 일치하는 관측 근거로 보유 상태를 확인한다. 기본 계정 존재나 license_active만으로 재사용을 추정하지 않는다.
PERMISSION_ONLY: 기존 라이선스 범위의 Notion 페이지 편집, Tableau 프로젝트 편집·게시, Salesforce 담당 고객 권한 추가는 라이선스 보유가 확인되면 추가 비용 0이다. 필요한 라이선스가 없으면 권한 요청을 자동 구매로 확대하지 않고 먼저 라이선스를 확보하도록 수동 검토한다.
PURCHASE_SEAT: 명시된 GitHub Copilot·Figma Full 좌석 요청은 해당 조직의 동일 상품 보유 여부를 확인한다. 이미 보유하면 추가 비용 0, 미보유가 확인되고 신규 구매 조건이 충족되면 서버 단가를 적용한다. 선구매 미배정 좌석 재사용·차액 업그레이드·일할 청구는 현재 자동 계산하지 않으며 그런 조건이면 근거 확인 후 별도 계획이 필요하다.
USAGE_ALLOCATION: Snowflake·Databricks의 금액은 권한 자체의 좌석 비용이 아니라 시연 정책에서 정한 내부 사용량 예산 배정이다. 실제 SaaS 청구액이나 이미 발생한 지출로 설명하지 않는다.
라이선스 사실이 없거나 UNKNOWN이거나 유효 기간이 지났으면 0으로 추정하지 않고 MANUAL_REVIEW로 보낸다. 금액·통화가 확인된 예산 배정액만 부서 예산과 비교하며, 부족하면 ON_HOLD/BUDGET_INSUFFICIENT다.
0원 요청도 정책·직무·업무 범위와 사람의 순차 승인을 유지한다. 승인과 실행 직전에 라이선스·예산 조건을 재확인하고 승인 금액이나 비용 기준이 바뀌면 재검토한다. 실행 차감은 내부 부서 예산 처리이며 실제 결제 API 호출이 아니다.

## BASELINE | TABLEAU_CLOUD | 4 | 기존 라이선스의 프로젝트 권한 추가

POL-13 제3조의 라이선스 비용 비교는 새 라이선스 확보가 필요한 경우에 적용한다. 현재 시연 신청자는 해당 사이트의 Explorer 라이선스 보유를 별도 관측으로 확인하며, 게시된 데이터 원본을 쓰는 프로젝트 편집·게시 권한 추가 비용은 0이다. Creator가 필요한 작업이나 다른 사이트 라이선스를 자동으로 포함하지 않는다.
'''
        files[DIRECTORY/f'company-{company.lower()}-policy-v4.md']=content
        sql.append(f'''DO $costs$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM companies WHERE id={co} AND code='P2_{company}' AND is_mock)
    OR NOT EXISTS(SELECT 1 FROM policy_revisions WHERE policy_id={policy} AND revision=3 AND source_hash={quote(digest(old))})
    OR EXISTS(SELECT 1 FROM policy_revisions WHERE company_id={co} AND (policy_id<>{policy} OR revision>4)) THEN
    RAISE EXCEPTION 'Unexpected source policy for access costs';
  END IF;
  INSERT INTO policy_revisions(policy_id,revision,company_id,doc_id,article,source_path,source_hash,content,is_mock)
    VALUES({policy},4,{co},'P2-{company}-POLICY','POL-01~14 / OFF / FLOW / cost rules',
      'data/phase2/policies/company-{company.lower()}-policy-v4.md',{quote(digest(content))},{quote(content)},true)
    ON CONFLICT(policy_id,revision) DO NOTHING;
  IF NOT EXISTS(SELECT 1 FROM policy_revisions WHERE policy_id={policy} AND revision=4 AND source_hash={quote(digest(content))} AND content={quote(content)}) THEN
    RAISE EXCEPTION 'Conflicting cost policy revision';
  END IF;''')
        for table,(key,fields) in COPY_COLUMNS.items():
            columns=[key,*fields.split(',')]
            selected=','.join(('4' if c in {'revision','policy_revision'} else c)+f' AS {c}' for c in columns)
            where=f'company_id={co} AND policy_id={policy} AND revision=3 AND policy_revision=3'
            expected=12 if table=='pricing_revisions' else 1 if table=='approval_route_revisions' else 2
            sql.append(f'''
  IF (SELECT count(*) FROM {table} WHERE {where})<>{expected} THEN RAISE EXCEPTION 'Incomplete cost revision source: {table}'; END IF;
  INSERT INTO {table}({','.join(columns)}) SELECT {selected} FROM {table} WHERE {where} ON CONFLICT({key},revision) DO NOTHING;
  IF EXISTS(SELECT to_jsonb(x) FROM (SELECT {selected} FROM {table} WHERE {where}) x
    EXCEPT SELECT to_jsonb(y) FROM {table} y WHERE company_id={co} AND revision=4) THEN
    RAISE EXCEPTION 'Conflicting cost revision bindings: {table}';
  END IF;''')
        items=[i for i in catalog['catalog'] if i['company']==company]
        for item in items:
            platform=item['platform']
            operation='USAGE_ALLOCATION' if item['cost_basis']=='USAGE_ESTIMATE' else 'PURCHASE_SEAT' if item['kind']=='SEAT' else 'PERMISSION_ONLY'
            license_data=licenses.get(platform)
            scope=f'p2-{company.lower()}-{platform.lower()}-billing' if license_data else None
            license=license_data[0] if license_data else None
            values=[co,quote(item['entitlement_id']),'1',policy,'4',quote(operation),quote(scope) if scope else 'NULL',quote(license) if license else 'NULL']
            sql.append(f"  INSERT INTO access_cost_rules(company_id,entitlement_id,entitlement_revision,policy_id,policy_revision,operation,billing_scope,required_license) VALUES({','.join(values)}) ON CONFLICT DO NOTHING;")
            scope_check=f'billing_scope={quote(scope)} AND required_license={quote(license)}' if scope else 'billing_scope IS NULL AND required_license IS NULL'
            sql.append(f"  IF NOT EXISTS(SELECT 1 FROM access_cost_rules WHERE company_id={co} AND entitlement_id={quote(item['entitlement_id'])} AND entitlement_revision=1 AND policy_id={policy} AND policy_revision=4 AND operation={quote(operation)} AND {scope_check}) THEN RAISE EXCEPTION 'Conflicting access cost rule'; END IF;")
            if license_data:
                purchase='true' if license_data[1]=='NOT_COVERED' else 'false'
                sql.append(f"  INSERT INTO saas_license_facts(company_id,user_id,platform,billing_scope,license_code,coverage,purchase_required,observed_at,source_reference) VALUES({co},{quote(info['users']['requester'])},{quote(platform)},{quote(scope)},{quote(license)},{quote(license_data[1])},{purchase},now(),'SYNTHETIC:scoped-cost-facts') ON CONFLICT DO NOTHING;")
        sql.append('END $costs$;')
    sql.append('COMMIT;')
    files[DIRECTORY/'apply-costs.sql']='\n'.join(sql)+'\n'
    scenarios=json.loads((ROOT/'data/phase2/scenarios-v4.json').read_text())
    scenarios.update(policy_revision=4,cost_model_version=1)
    for case in scenarios['scenarios']:
        if case['id']=='E-02':
            case.update(expected_status='WAITING_APPROVAL',expected_reason_code='ELIGIBLE',decision_rule='NO_ADDITIONAL_COST',
                expected_evidence=[['POL-06','제2조'],['POL-08','제3조']])
            case['preconditions'].update(monthly_amount='0.00',unit_monthly_amount='20.00',cost_basis='NO_ADDITIONAL_COST',
                policy_revision=4,pricing_revision=4,operation='PERMISSION_ONLY',license_coverage='COVERED',purchase_required=False)
        if case['id']=='P-05':
            case['decision_rule']='NO_ADDITIONAL_COST'
            case['preconditions']={**next(c for c in scenarios['scenarios'] if c['id']=='E-02')['preconditions'],
                'entitlement_code':'PROJECT_PUBLISHER','access_scope':'GENERAL','unit_monthly_amount':'70.00',
                'remaining_budget':case['overrides'].get('budget','500.00'),'tf_member':False}
    files[ROOT/'data/phase2/scenarios-current.json']=json.dumps(scenarios,ensure_ascii=False,indent=2)+'\n'
    return files


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for path,content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text()!=content:raise SystemExit(f'Stale access cost file: {path}')
        else:path.write_text(content)
    print('Access cost files verified' if args.check else 'Access cost revision generated')
